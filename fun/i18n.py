def t(locale: str, key: str) -> str:
    language = "zh-CN" if locale.startswith("zh") else "en-US"
    return TEXT[language].get(key, TEXT["en-US"].get(key, key))


#: Where ``FunConfig.save`` left the key -> the message that tells the truth.
_SAVED_BY_LOCATION = {
    "keychain": "saved",
    "config-file": "saved_to_file",
    "environment": "saved_not_durable",
    "none": "saved_not_durable",
}

_WHERE_BY_LOCATION = {
    "keychain": "key_where_keychain",
    "config-file": "key_where_file",
    "environment": "key_where_env",
    "none": "key_where_none",
}


def saved_message(locale: str, location: str, path: str) -> str:
    """Confirm a save by naming where the key actually landed.

    Both save paths used to print a flat "saved" line, so a machine where the
    keychain write failed looked exactly like one where it worked — which is
    how a configured key could silently vanish by the next morning.
    """
    return t(locale, _SAVED_BY_LOCATION.get(location, "saved_not_durable")).format(path=path)


def key_location_message(locale: str, location: str, path: str) -> str:
    """One line for ``/status``: where this machine reads the key from."""
    return t(locale, _WHERE_BY_LOCATION.get(location, "key_where_none")).format(path=path)
